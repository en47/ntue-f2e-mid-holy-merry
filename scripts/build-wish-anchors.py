#!/usr/bin/env python3
"""Build branch anchors without changing the GLB, textures, or wish data.
Requires Pillow. This tree has one identity-transform mesh; fail rather than
silently producing incorrect points if that source structure changes.
Candidates must lie on green outward-facing vertices, and their conservative
paper-body box must clear sampled red/orange decorations. Browser assignments
add body-to-body separation and stable stratification.
"""
import struct,json,math,io,pathlib,hashlib
from PIL import Image
ROOT=pathlib.Path(__file__).resolve().parents[1]
b=(ROOT/'assets/models/wish-tree.glb').read_bytes();n=struct.unpack_from('<I',b,12)[0];d=json.loads(b[20:20+n]);binary=memoryview(b)[28+n:]
assert len(d['nodes'])==1 and not any(k in d['nodes'][0] for k in ('matrix','translation','rotation','scale')), 'Inspect changed model transforms before regenerating anchors'
def data(i):
 a=d['accessors'][i];v=d['bufferViews'][a['bufferView']];off=v.get('byteOffset',0)+a.get('byteOffset',0);size={'VEC3':3,'VEC2':2}[a['type']];return list(struct.iter_unpack('<'+'f'*size,binary[off:off+a['count']*size*4]))
v=d['bufferViews'][d['images'][0]['bufferView']];im=Image.open(io.BytesIO(binary[v['byteOffset']:v['byteOffset']+v['byteLength']])).convert('RGB');pix=im.load();iw,ih=im.size
p=data(0); normals=data(1);uv=data(2);h=d['accessors'][0]['max'][1];green=[];ornaments=[]
for i,((x,y,z),(u,v),(nx,ny,nz)) in enumerate(zip(p,uv,normals)):
 r,g,bl=pix[min(iw-1,int(u*iw)),min(ih-1,int(v*ih))];q=(x/h,y/h,z/h);rad=math.hypot(x,z)
 if g>r*1.08 and g>bl*1.06 and rad>.03 and (nx*x+nz*z)/rad>.12:green.append((i,q,rad/h,math.atan2(x,z)))
 if r>g*1.4 and r>bl*1.4 and r>90 and i%3==0:ornaments.append(q)
print('bbox',d['accessors'][0]['min'],d['accessors'][0]['max'],'height',h,'green',len(green),'red ornament samples',len(ornaments))
anchors=[]
for zone,ys in [('upper',[.68,.75]),('middle',[.46,.54,.61]),('lower',[.21,.27,.34,.40])]:
 for yi,y in enumerate(ys):
  for s in range(12):
   angle=-math.pi+s*math.pi/6+(.05 if yi%2 else -.05); pool=[a for a in green if abs(a[1][1]-y)<.018 and abs((a[3]-angle+math.pi)%(2*math.pi)-math.pi)<.15]
   pool.sort(key=lambda a:-a[2]);chosen=None
   for a in pool[:150]:
    x,yy,z=a[1];theta=a[3];sa,ca=math.sin(theta),math.cos(theta)
    # Conservative local body box, including narrow size/tilt and clearance variation.
    blocked=any(abs((ox-x)*ca-(oz-z)*sa)<.061 and -.105<oy-yy<.012 and -.012<(ox-x)*sa+(oz-z)*ca<.105 for ox,oy,oz in ornaments)
    if not blocked:chosen=a;break
   if chosen:anchors.append({'id':f'{zone}-{yi}-{s}','zone':zone,'vertex':chosen[0],'point':[round(v,7) for v in chosen[1]],'angle':round(chosen[3],7)})
# Real-triangle ray checks reject concave pockets rather than extending the string
# farther away from the tree. The second set also checks both PNG centers at +/-6
# degree rest tilt with the shorter .12 drop / .36 outset. Source GLB stays intact.
excluded={'lower-0-6','lower-2-1',
          'middle-0-3','middle-0-7','middle-0-8','middle-2-0','middle-2-1','middle-2-2',
          'lower-0-11','lower-2-10','lower-3-0'}
anchors=[a for a in anchors if a['id'] not in excluded]
print('anchors',len(anchors),{z:sum(a['zone']==z for a in anchors) for z in ['upper','middle','lower']})
metadata={'source':'assets/models/wish-tree.glb','sha256':hashlib.sha256(b).hexdigest(),'sourceHeight':h,'bounds':{'min':d['accessors'][0]['min'],'max':d['accessors'][0]['max']},'redSampleStride':3,'normalization':'x/z from bounding-box center; y from ground; all divided by model height'}
(ROOT/'js/data/wish-tree-anchors.js').write_text('// Generated by scripts/build-wish-anchors.py from the existing GLB. Do not hand-edit.\nexport const wishTreeAnchorSource = '+json.dumps(metadata,ensure_ascii=False,separators=(',',':'))+';\nexport const wishTreeAnchors = '+json.dumps(anchors,ensure_ascii=False,separators=(',',':'))+';\n')
